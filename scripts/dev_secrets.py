#!/usr/bin/env python3
"""Create local development secrets and a matching services/api/.env.

Usage (from the repository root):
    python scripts/dev_secrets.py

Writes random values into ./secrets/ (git-ignored) for Docker Compose, and a
services/api/.env (git-ignored) pointing the API at the dev database. Existing
files are never overwritten, so re-running it is safe; delete a file to rotate it.

For development only. A production deployment generates its own secrets and
stores them outside the repository.
"""

from __future__ import annotations

import base64
import secrets
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SECRETS = ROOT / "secrets"
API_ENV = ROOT / "services" / "api" / ".env"

_PASSWORDS = ("db_superuser_password", "db_migrator_password", "db_app_password")
_DEV_DB = "127.0.0.1:55432/humani_t"


def _write_once(path: Path, value: str) -> str:
    if path.exists():
        return path.read_text(encoding="utf-8").strip()
    path.write_text(value, encoding="utf-8", newline="\n")
    print(f"created {path.relative_to(ROOT)}")
    return value


def main() -> None:
    SECRETS.mkdir(exist_ok=True)
    values = {name: _write_once(SECRETS / name, secrets.token_urlsafe(32)) for name in _PASSWORDS}
    kek = _write_once(
        SECRETS / "key_encryption_keys",
        f"1:{base64.b64encode(secrets.token_bytes(32)).decode()}",
    )

    env = (
        "# Generated by scripts/dev_secrets.py for local development. Never commit.\n"
        "HUMANI_T_ENVIRONMENT=development\n"
        f"HUMANI_T_DATABASE_URL=postgresql+asyncpg://humani_t_app:{values['db_app_password']}@{_DEV_DB}\n"
        "HUMANI_T_MIGRATION_DATABASE_URL="
        f"postgresql+asyncpg://humani_t_migrator:{values['db_migrator_password']}@{_DEV_DB}\n"
        f"HUMANI_T_KEY_ENCRYPTION_KEYS={kek}\n"
    )
    _write_once(API_ENV, env)


if __name__ == "__main__":
    main()
